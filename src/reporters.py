def _register_cyberlab_pdf_fonts() -> tuple[str, str]:
    """PDF için Türkçe karakterleri destekleyen font çiftini kaydeder."""

    candidates = [
        (
            Path(r"C:\Windows\Fonts\segoeui.ttf"),
            Path(r"C:\Windows\Fonts\segoeuib.ttf"),
            "CyberLabSegoe",
            "CyberLabSegoeBold",
        ),
        (
            Path(r"C:\Windows\Fonts\arial.ttf"),
            Path(r"C:\Windows\Fonts\arialbd.ttf"),
            "CyberLabArial",
            "CyberLabArialBold",
        ),
        (
            Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"),
            Path("/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"),
            "CyberLabDejaVu",
            "CyberLabDejaVuBold",
        ),
    ]

    for regular_path, bold_path, regular_name, bold_name in candidates:
        if regular_path.exists() and bold_path.exists():
            if regular_name not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(
                    TTFont(regular_name, str(regular_path))
                )
            if bold_name not in pdfmetrics.getRegisteredFontNames():
                pdfmetrics.registerFont(
                    TTFont(bold_name, str(bold_path))
                )
            return regular_name, bold_name

    return "Helvetica", "Helvetica-Bold"


def _pdf_paragraph(
    value: Any,
    style: ParagraphStyle,
) -> Paragraph:
    """Bir değeri güvenli bir ReportLab paragrafına dönüştürür."""

    text = html.escape(str(value if value is not None else "—"))
    return Paragraph(text, style)


def _cyberlab_pdf_page(
    canvas,
    doc,
    regular_font: str,
    bold_font: str,
) -> None:
    """Ortak PDF altbilgisini ve sayfa numarasını çizer."""

    canvas.saveState()
    width, _height = landscape(A4)
    canvas.setStrokeColor(colors.HexColor("#CBD5E1"))
    canvas.setLineWidth(0.5)
    canvas.line(
        doc.leftMargin,
        10 * mm,
        width - doc.rightMargin,
        10 * mm,
    )
    canvas.setFont(regular_font, 8)
    canvas.setFillColor(colors.HexColor("#64748B"))
    canvas.drawString(
        doc.leftMargin,
        6 * mm,
        "Generated by CyberLab Desktop Security Suite",
    )
    canvas.setFont(bold_font, 8)
    canvas.drawRightString(
        width - doc.rightMargin,
        6 * mm,
        f"Sayfa {doc.page}",
    )
    canvas.restoreState()


def save_json_report(
    report: dict[str, Any],
    output_file: Path,
) -> Path:
    """Tam analiz raporunu JSON formatında kaydeder."""

    ensure_directory(output_file.parent)

    with output_file.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            report,
            file,
            ensure_ascii=False,
            indent=2,
        )

    return output_file


def save_network_csv(
    report: dict[str, Any],
    output_file: Path,
) -> Path:
    """Tespit edilen ağları CSV formatında kaydeder."""

    ensure_directory(output_file.parent)

    with output_file.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:
        writer = csv.writer(file)

        writer.writerow(
            [
                "SSID",
                "BSSID",
                "Kanal",
                "Ortalama_Sinyal_dBm",
                "Istemci_Sayisi",
            ]
        )

        for network in report["networks"]:
            writer.writerow(
                [
                    " | ".join(network["ssids"]),
                    network["bssid"],
                    network["channel"],
                    network["average_signal_dbm"],
                    len(network["clients"]),
                ]
            )

    return output_file


def save_clients_csv(
    report: dict[str, Any],
    output_file: Path,
) -> Path:
    """Ağ ve istemci ilişkilerini CSV formatında kaydeder."""

    ensure_directory(output_file.parent)

    with output_file.open(
        "w",
        encoding="utf-8",
        newline="",
    ) as file:
        writer = csv.writer(file)

        writer.writerow(
            [
                "BSSID",
                "SSID",
                "Istemci_MAC",
                "Paket_Sayisi",
            ]
        )

        for network in report["networks"]:
            ssid_text = " | ".join(network["ssids"])

            for client in network["clients"]:
                writer.writerow(
                    [
                        network["bssid"],
                        ssid_text,
                        client["mac"],
                        client["packet_count"],
                    ]
                )

    return output_file


