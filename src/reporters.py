def generate_all_reports(
    report: dict[str, Any],
    reports_dir: Path,
    base_name: str,
    capture_name: str,
) -> list[Path]:
    """Tüm rapor formatlarını tek seferde üretir."""

    ensure_directory(reports_dir)

    created_files = [
        save_json_report(
            report,
            reports_dir / f"{base_name}.json",
        ),
        save_network_csv(
            report,
            reports_dir / f"{base_name}_networks.csv",
        ),
        save_clients_csv(
            report,
            reports_dir / f"{base_name}_clients.csv",
        ),
        save_html_report(
            report,
            reports_dir / f"{base_name}.html",
            capture_name,
        ),
    ]

    return created_files

def export_json_report(
    report: dict,
    output_dir: Path,
) -> Path:
    """CyberLab analiz sonucunu JSON raporu olarak kaydeder."""

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    timestamp = datetime.now().strftime(
        "%Y%m%d_%H%M%S"
    )

    output_path = (
        output_dir
        / f"cyberlab_report_{timestamp}.json"
    )

    payload = {
        "product": "CyberLab",
        "module": "Wi-Fi Forensics",
        "generated_at": datetime.now().isoformat(
            timespec="seconds"
        ),
        "report": report,
    }

    with output_path.open(
        "w",
        encoding="utf-8",
    ) as file:
        json.dump(
            payload,
            file,
            indent=4,
            ensure_ascii=False,
            default=str,
        )

    return output_path


